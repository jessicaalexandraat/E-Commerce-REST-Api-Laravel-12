<?php

namespace App\Http\Controllers;

use App\Models\Order;
use App\Models\Payment;
use Illuminate\Http\Request;
use Stripe\Stripe;
use Stripe\Charge;
use Exception;

class PaymentController extends Controller
{
    /**
     * Procesar pago de una orden mediante Stripe
     */
    public function processPayment(Request $request)
    {
        $request->validate([
            'order_id'     => 'required|exists:orders,id',
            'stripe_token' => 'required|string', // Token de prueba generado por frontend/Stripe (ej: tok_visa)
        ]);

        $order = Order::where('user_id', auth('api')->id())
            ->where('id', $request->order_id)
            ->first();

        if (!$order) {
            return response()->json(['message' => 'Orden no encontrada o no pertenece al usuario'], 404);
        }

        if ($order->status === 'paid') {
            return response()->json(['message' => 'Esta orden ya ha sido pagada previamente'], 400);
        }

        try {
            // Establecer la clave secreta de Stripe
            Stripe::setApiKey(config('services.stripe.secret'));

            // Crear el cargo en Stripe (monto en centavos)
            $charge = Charge::create([
                'amount'      => (int) ($order->total_amount * 100),
                'currency'    => 'usd',
                'source'      => $request->stripe_token,
                'description' => "Pago de orden #{$order->id} - Usuario ID: {$order->user_id}",
            ]);

            // Registrar el pago en la base de datos
            $payment = Payment::create([
                'order_id'          => $order->id,
                'stripe_payment_id' => $charge->id,
                'amount'            => $order->total_amount,
                'status'            => 'succeeded',
            ]);

            // Actualizar estado de la orden
            $order->update(['status' => 'paid']);

            return response()->json([
                'message' => 'Pago procesado exitosamente',
                'payment' => $payment,
                'order'   => $order
            ], 200);

        } catch (Exception $e) {
            // Registrar intento de pago fallido
            Payment::create([
                'order_id'          => $order->id,
                'stripe_payment_id' => null,
                'amount'            => $order->total_amount,
                'status'            => 'failed',
            ]);

            return response()->json([
                'error'   => 'Error al procesar el pago con Stripe',
                'details' => $e->getMessage()
            ], 500);
        }
    }
}










































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































